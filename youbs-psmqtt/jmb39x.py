SECTEUR = 512
CODE_REQUETE = 0x197b0322  # JMB39x "various devices" (meme code dans HW RAID Manager)
CODE_REVEIL = 0x197b0325
REVEIL = [(0x3c75a80b, 0x706d10d9), (0x0388e337, 0x6958511e),
          (0x689705f3, 0xfe234b07), (0xe00c523a, 0x5be57adb)]


def _crc_table():
    table = []
    for i in range(256):
        c = i << 24
        for _ in range(8):
            c = ((c << 1) ^ 0x04c11db7) if c & 0x80000000 else (c << 1)
        table.append(c & 0xffffffff)
    return table


CRC_TABLE = _crc_table()


def crc(data):
    c = 0x52325032
    for i in range(0, SECTEUR - 4, 4):
        dw = struct.unpack_from(">I", data, i)[0]
        for sh in (0, 8, 16, 24):
            c = (CRC_TABLE[((dw >> sh) & 0xff) ^ (c >> 24)] ^ (c << 8)) & 0xffffffff
    return c


def crc_ok(data):
    return struct.unpack_from("<I", data, SECTEUR - 4)[0] == crc(data)


def xor(data):
    return bytes(a ^ b for a, b in zip(data, XOR_TABLE))


def secteur_reveil(n):
    code, c = REVEIL[n]
    d = bytearray(SECTEUR)
    struct.pack_into("<II", d, 0, CODE_REVEIL, code)
    for i in range(16, SECTEUR - 8):
        d[i] = i & 0xff
    struct.pack_into("<II", d, SECTEUR - 8, 0x10eca1db, c)
    return bytes(d)


def secteur_requete(cmd_id, cmd):
    assert 4 <= len(cmd) <= 24
    d = bytearray(SECTEUR)
    struct.pack_into("<II", d, 0, CODE_REQUETE, cmd_id)
    d[8:8 + len(cmd)] = cmd
    struct.pack_into("<I", d, SECTEUR - 4, crc(d))
    return bytes(d)


def autotest():
    """Valeurs de controle de smartmontools (jmb_check_funcs)."""
    for n in range(4):
        assert crc_ok(secteur_reveil(n)), n
    assert crc(xor(secteur_reveil(2))) == 0x053ed64b
    r = secteur_requete(42, bytes([1, 2, 3, 4, 5, 6, 7]))
    assert struct.unpack_from("<I", r, SECTEUR - 4)[0] == 0xb1f765d7
    assert not crc_ok(xor(r)) and crc_ok(xor(xor(r)))


class SecteurNonVide(Exception):
    pass


class Session:
    """Ouvre le volume en acces direct (sans cache), sauvegarde le secteur de
    dialogue, reveille la puce ; a la fermeture, remet le secteur d'origine."""

    def __init__(self, dev, lba=33):
        self.dev, self.lba = dev, lba
        self.fd = None
        self.buf = mmap.mmap(-1, 4096)  # tampon aligne pour O_DIRECT
        self.origine = None
        self.cmd_id = 1

    def _lire(self):
        os.preadv(self.fd, [memoryview(self.buf)[:SECTEUR]], self.lba * SECTEUR)
        return bytes(self.buf[:SECTEUR])

    def _ecrire(self, data):
        self.buf[:SECTEUR] = data
        n = os.pwritev(self.fd, [memoryview(self.buf)[:SECTEUR]], self.lba * SECTEUR)
        if n != SECTEUR:
            raise OSError(f"ecriture incomplete du secteur {self.lba}")

    def __enter__(self):
        self.fd = os.open(self.dev, os.O_RDWR | os.O_DIRECT | os.O_SYNC)
        try:
            self.origine = self._lire()
            if any(self.origine):
                raise SecteurNonVide(f"secteur {self.lba} de {self.dev} non vide : rien n'est ecrit")
            for n in range(4):
                self._ecrire(secteur_reveil(n))
        except BaseException:
            if self.origine is not None and not any(self.origine):
                try:
                    self._ecrire(self.origine)
                except OSError:
                    pass
            os.close(self.fd)
            raise
        return self

    def __exit__(self, *exc):
        try:
            self._ecrire(self.origine)
            if self._lire() != self.origine:
                raise OSError(f"secteur {self.lba} mal restaure")
        finally:
            os.close(self.fd)

    def commande(self, groupe, cmd, param, args=b""):
        c = bytearray(24)
        c[0:5] = bytes([0x00, groupe, cmd, 0xff, param])
        c[8:8 + len(args)] = args
        req = secteur_requete(self.cmd_id, bytes(c))
        self._ecrire(xor(req))
        rep = xor(self._lire())
        if rep == req:
            raise OSError("pas de reponse de la puce JMB39x")
        if not crc_ok(rep):
            raise OSError("reponse JMB39x invalide (CRC)")
        if rep[:8] != req[:8]:
            raise OSError("en-tete de reponse JMB39x invalide")
        self.cmd_id += 1
        return rep

    def info_raid(self, n):
        """Commande (3, 2, n) de HW RAID Manager : charge utile de 0x1a4
        octets a partir de l'octet 12 de la reponse."""
        rep = self.commande(3, 2, n, bytes([n]))
        return rep[12:12 + 0x1a4]


def texte(b):
    return b.split(b"\0")[0].decode("ascii", "replace").strip()


def ata(b):
    """Chaine ATA : octets inverses deux a deux."""
    return texte(bytes(x for i in range(0, len(b) - 1, 2) for x in (b[i + 1], b[i])))


# Tables de HW RAID Manager (0x1082620 et 0x1082640 dans HWRaidManager.exe)
NIVEAUX = ["RAID 0", "RAID 1", "LARGE", "RAID 3", "CLONE", "RAID 5", "RAID 10"]
ETATS = ["Cassé", "Dégradé", "En reconstruction", "Normal", "Extension", "Sauvegarde"]
ETAT_NORMAL = 3


def decoder_raid(p):
    """Volume RAID decrit par la commande (3, 2, n), ou None si absent.
    Offsets releves dans HW RAID Manager et verifies sur le boitier Orico
    (RAID 5 de 5 disques, etat Normal)."""
    if p[1] == 0x0f:
        return None
    etat, niveau = p[0x46], p[0x54]
    membres = [p[0xa0 + 0x20 * i + 0xb] + 1 for i in range(5) if p[0xa0 + 0x20 * i + 4]]
    return {
        "nom": ata(p[4:4 + 40]),
        "serie": ata(p[0x2c:0x2c + 20]),
        "etat": ETATS[etat] if etat < len(ETATS) else f"Inconnu ({etat})",
        "etat_code": etat,
        "niveau": NIVEAUX[niveau] if niveau < len(NIVEAUX) else f"Inconnu ({niveau})",
        "nb_disques": p[0x55],
        "disques": membres,
    }


